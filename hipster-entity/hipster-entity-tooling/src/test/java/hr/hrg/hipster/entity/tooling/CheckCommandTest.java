package hr.hrg.hipster.entity.tooling;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/** E5: `--check` is a real full pass into a temp tree, and it never touches the committed tree. */
@Tag("generator")
class CheckCommandTest {

    @Test
    void currentTreePassesAndAChangedViewFailsWithoutWriting() throws Exception {
        ExamplePassFixture fixture = ExamplePassFixture.create();
        Path sourceRoot = fixture.sourceRoot();
        Path reportDir = fixture.reportDir();
        EntityMetadataGenerator.setGenerateDtoProjections(true);
        EntityMetadataGenerator.setMapperRequests(List.of("PersonSummary:PersonDto"));
        try {
            // The fixture itself is a plain pass; run the same optional flags gen.js uses so the
            // committed tree really is what --check would produce.
            EntityMetadataGenerator.generate(sourceRoot, reportDir, sourceRoot);
            Assertions.assertEquals(0,
                    EntityMetadataGenerator.checkGeneratedSource(sourceRoot, reportDir, sourceRoot),
                    "a tree just generated by the same flags is current");

            Path generated = sourceRoot.resolve(
                    "hr/hrg/hipster/entityexample/person/entity/PersonDetails_.java");
            byte[] original = Files.readAllBytes(generated);
            Files.writeString(generated, Files.readString(generated) + "\n// deliberate drift\n");
            Assertions.assertEquals(1,
                    EntityMetadataGenerator.checkGeneratedSource(sourceRoot, reportDir, sourceRoot),
                    "a hand-edited generated file is reported as stale");
            Files.write(generated, original);

            Path view = sourceRoot.resolve(
                    "hr/hrg/hipster/entityexample/person/entity/PersonDetails.java");
            String source = Files.readString(view);
            Files.writeString(view, source.replace("String email();",
                    "String email();\n    String nickname();"));
            byte[] before = Files.readAllBytes(generated);

            Assertions.assertEquals(1,
                    EntityMetadataGenerator.checkGeneratedSource(sourceRoot, reportDir, sourceRoot),
                    "an edited view is reported as stale");
            Assertions.assertArrayEquals(before, Files.readAllBytes(generated),
                    "--check must not write the committed generated file");
        } finally {
            EntityMetadataGenerator.setGenerateDtoProjections(false);
            EntityMetadataGenerator.setMapperRequests(List.of());
        }
    }
}
