#!/usr/bin/env bun
/**
 * `generate-migration-report` — Phase 6 deliverable 2, script 4.
 *
 * <p>Writes the report in exactly the format the plan specifies
 * (`06-Migration-Checklist.md` § Migration Report Format): summary counts, files
 * migrated, issues encountered, recommendations. The sections are the plan's; the
 * content is measured from the scan and the tracker, so the report cannot claim a
 * file is migrated that still imports JavaParser.
 *
 * <p>Usage:
 * <pre>
 *   bun run scripts/rewrite-migration/generate-migration-report.js [--out FILE]
 * </pre>
 *
 * <p>Without `--out` the report goes to stdout, so it is safe to run at any time.
 * The plan's `reports/` location is per-module and gitignored by default
 * (DEC-026), so this script does not choose a path for you.
 */

import { writeFileSync } from 'node:fs';

import { buildModel, progressOf, inWorkOrder, TRACKER_PATH } from './model.js';
import { PREREQUISITES } from './curation.js';
import { mappingStats, OPENREWRITE_VERSION, JAVAPARSER_VERSION } from './mappings.js';
import { parseArgs, resolveRoot, out, warn, UsageError } from './cli.js';

const USAGE = `usage: bun run scripts/rewrite-migration/generate-migration-report.js [--root DIR] [--out FILE]`;

async function main() {
  const { flags } = parseArgs(process.argv.slice(2), { root: 'string', out: 'string' });
  const root = resolveRoot(flags);
  const model = await buildModel(root);
  const markdown = render(model);

  if (typeof flags.out === 'string') {
    writeFileSync(flags.out, markdown);
    warn(`wrote ${flags.out}`);
    return;
  }
  process.stdout.write(markdown);
}

function render(model) {
  const progress = progressOf(model);
  const mappings = mappingStats();
  const lines = [];
  const push = (line = '') => lines.push(line);

  push('# Migration Report');
  push();
  push(`Generated by \`scripts/rewrite-migration/generate-migration-report.js\` — do not edit by hand.`);
  push();
  push(`| | |`);
  push(`| --- | --- |`);
  push(`| Repository | \`${model.root}\` |`);
  push(`| Generated | ${new Date().toISOString()} |`);
  push(`| Tracker | \`${TRACKER_PATH}\` |`);
  push(`| JavaParser version leaving | ${JAVAPARSER_VERSION} |`);
  push(`| OpenRewrite version arriving | ${OPENREWRITE_VERSION} |`);
  push();

  // ---- Summary -------------------------------------------------------------
  push('## Summary');
  push();
  push('| Measure | Count |');
  push('| --- | --- |');
  push(`| Java files in the tree (excluding build output and worktrees) | ${model.javaFilesTotal} |`);
  push(`| Files mentioning JavaParser | ${model.totals.javaFilesWithAnyMention} |`);
  push(`| JavaParser import lines (whole tree) | ${model.totals.imports} |`);
  push(`| Files in the migration queue | ${progress.total} |`);
  push(`| … main sources | ${progress.scope.main} |`);
  push(`| … test sources | ${progress.scope.test} |`);
  push(`| … other | ${progress.scope.other} |`);
  push(`| Files migrated (import-free, port not yet verified) | ${progress.importFree} |`);
  push(`| Files settled (complete or exempt) | ${progress.settled} |`);
  push(`| Files remaining | ${progress.remaining} |`);
  push(`| Files still importing JavaParser | ${progress.stillImporting} |`);
  push(`| Files unclassified by curation | ${model.unclassifiedFiles.length} |`);
  push(`| Files exempt (allowlisted) | ${model.exemptFiles.length} |`);
  push(
    `| Success rate (settled / queue) | ${progress.percentSettled}% |`,
  );
  push();

  push('### Status breakdown');
  push();
  push('| Status | Files |');
  push('| --- | --- |');
  for (const [status, count] of Object.entries(progress.byStatus)) {
    if (count > 0) {
      push(`| \`${status}\` | ${count} |`);
    }
  }
  push();

  push('### Mapping coverage');
  push();
  push(
    `The report counts a mapping as **verified** only when the OpenRewrite side is already ` +
      `used in this repository (\`merge-java\`). Everything else is a documented LST type that ` +
      `no file here exercises yet, and is reported as **inferred**.`,
  );
  push();
  push('| Mapping kind | Count |');
  push('| --- | --- |');
  push(`| verified | ${mappings.verified} |`);
  push(`| inferred | ${mappings.inferred} |`);
  push(`| total | ${mappings.total} |`);
  push();

  // ---- Files migrated ------------------------------------------------------
  push('## Files Migrated');
  push();
  const complete = inWorkOrder(model.queueFiles).filter((f) => f.status === 'complete');
  if (complete.length === 0) {
    push('None yet. Phase 6 is at the checklist stage; see `## Issues Encountered` for the');
    push('prerequisites that block the first port.');
  } else {
    for (const file of complete) {
      push(`- \`${file.repoPath}\` — Complete`);
    }
  }
  push();

  push('## Files In Progress');
  push();
  const inProgress = inWorkOrder(model.queueFiles).filter(
    (f) => f.status === 'in-progress' || f.status === 'testing',
  );
  if (inProgress.length === 0) {
    push('None.');
  } else {
    for (const file of inProgress) {
      push(`- \`${file.repoPath}\` — ${file.status}`);
    }
  }
  push();

  push('## Files Remaining');
  push();
  const remaining = inWorkOrder(model.queueFiles).filter(
    (f) => f.status === 'not-started' || f.status === 'blocked',
  );
  push('| Priority | Risk | Status | JavaParser imports | File |');
  push('| --- | --- | --- | --- | --- |');
  for (const file of remaining) {
    push(
      `| ${file.priority} | ${file.risk ?? '-'} | \`${file.status}\` | ${file.imports.length} | \`${file.repoPath}\` |`,
    );
  }
  push();

  // ---- Issues --------------------------------------------------------------
  push('## Issues Encountered');
  push();
  const openPrereqs = PREREQUISITES.filter((p) => !p.done);
  if (openPrereqs.length === 0) {
    push('None recorded.');
  } else {
    for (const prereq of openPrereqs) {
      push(`### ${prereq.id} — ${prereq.title}`);
      push();
      push(prereq.why);
      push();
      push(`Evidence: ${prereq.evidence}`);
      push();
    }
  }
  push('### Known mapping risks');
  push();
  push('Two mappings are singled out in `mappings.js` as producing *wrong output rather');
  push('than a compile error* if ported mechanically:');
  push();
  push('- `ast.comments.Comment` has no LST node. Comment text becomes a prefix on the');
  push('  following tree, so comment *identity and position* — which DEC-020 block');
  push('  recognition and enum-order holding both depend on — is not preserved by a');
  push('  rename.');
  push('- `ast.Range` has no LST equivalent. Line/column becomes a character offset that');
  push('  must be resolved back to a line, so a location compared against a saved location');
  push('  can shift silently.');
  push();

  // ---- Recommendations -----------------------------------------------------
  push('## Recommendations');
  push();
  push('1. **Clear the Phase-0 prerequisites before porting anything.** The staging code');
  push('   Phase 6 was meant to build on does not compile, and a port cannot be verified');
  push('   against a build that was already broken.');
  push('2. **Port the read path first.** `SourceReader` is the single seam for 33 of the');
  push('   34 queue files; proving it alone de-risks the rest.');
  push('3. **Port `CooperativeCodegen` last, with tests on both sides.** It is the only');
  push('   file where a compiling port can start overwriting hand-edited generated code.');
  push('4. **Keep `clean` in the gate.** This repository already records a case (note F-47)');
  push('   where a non-clean build reported success from stale classes; that is how the');
  push('   staging breakage stayed invisible.');
  push('5. **Do not remove `javaparser-core` until the allowlisted test is re-expressed.**');
  push('   `SourceReaderTest` asserts the parser language level, which is the regression');
  push('   guard behind notes F-23/F-34.');
  push('6. **Fix the plan’s file list.** It names `webview-jetbrains` paths that do not');
  push('   exist and omits the seven files whose JavaParser use is fully qualified.');
  push();

  return `${lines.join('\n')}\n`;
}

try {
  await main();
} catch (error) {
  if (error instanceof UsageError) {
    warn(`${error.message}\n${USAGE}`);
    process.exit(2);
  }
  throw error;
}
