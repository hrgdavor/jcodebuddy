#!/usr/bin/env bun
/**
 * Builds the merge-java review page: the report is inlined at build time (so the page opens from
 * `file://` with no server and no fetch — a `fetch()` of a sibling JSON is blocked by CORS on
 * `file://`), then esbuild bundles the JSX against the local jsx6 checkout.
 *
 * Usage:
 *   bun run src_build/build.js [--report <path>] [--out <dir>] [--dev]
 *
 * Defaults: --report <merge-java>/.jcodebuddy/metadata/merge-report.json when it exists, else the
 * committed sample-report.json; --out build/
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { esbDef, jsx6Root, libraryAliases } from './esbDef.js'

const here = dirname(fileURLToPath(import.meta.url))
const packageRoot = resolve(here, '..')
const repoRoot = resolve(packageRoot, '../..')
const mergeJavaRoot = resolve(packageRoot, '..')

const args = process.argv.slice(2)
const valueOf = (flag, fallback) => {
  const index = args.indexOf(flag)
  return index >= 0 && index + 1 < args.length ? args[index + 1] : fallback
}
const dev = args.includes('--dev')
const outDir = resolve(valueOf('--out', join(packageRoot, 'build')))
const defaultReport = join(mergeJavaRoot, '.jcodebuddy', 'metadata', 'merge-report.json')
const sampleReport = join(packageRoot, 'sample-report.json')
const reportPath = resolve(valueOf('--report', defaultReport))

let reportSource = reportPath
let reportJson
try {
  reportJson = readFileSync(reportSource, 'utf8')
} catch {
  reportSource = sampleReport
  reportJson = readFileSync(reportSource, 'utf8')
}
// Parse here rather than trusting the file: a malformed report must fail the build, not the page.
const report = JSON.parse(reportJson)

// The generated module is what the page imports; it lives outside src/ so generated output never
// mixes with source, and the source path travels with it so the page can say where its data is from.
const generatedDir = join(packageRoot, '.generated')
mkdirSync(generatedDir, { recursive: true })
writeFileSync(
  join(generatedDir, 'report.js'),
  `// @generated by src_build/build.js — do not edit.\n` +
    `export const reportSource = ${JSON.stringify(reportSource)}\n` +
    `export const isSample = ${reportSource === sampleReport}\n` +
    `export const report = ${JSON.stringify(report, null, 2)}\n`,
)

const root = jsx6Root(repoRoot)
const aliases = libraryAliases(root)
const esbuildArgs = [
  'esbuild',
  join(packageRoot, 'src', 'index.jsx'),
  `--outfile=${join(outDir, 'review.js')}`,
  '--bundle',
  `--format=${esbDef.format}`,
  `--jsx=${esbDef.jsx}`,
  `--jsx-import-source=${esbDef.jsxImportSource}`,
  `--tsconfig=${join(packageRoot, esbDef.tsconfig)}`,
  '--sourcemap',
  ...Object.entries(esbDef.loader).map(([ext, loader]) => `--loader:${ext}=${loader}`),
  ...Object.entries(aliases).map(([name, entry]) => `--alias:${name}=${entry}`),
  ...(dev ? ['--jsx-dev'] : []),
]

mkdirSync(outDir, { recursive: true })
console.log(`[review] report:  ${reportSource}${reportSource === sampleReport ? '  (sample)' : ''}`)
console.log(`[review] jsx6:    ${root}  (${Object.keys(aliases).length} libs aliased)`)
console.log(`[review] out:     ${outDir}`)

// The CLI with inherited stdio, not the JS API: jsx6's agent-rules note that the JS API spawns a
// piped service, which a confined sandbox denies with EPERM (jsx6/docs/stack/agent-rules.md).
const build = Bun.spawnSync(['bunx', ...esbuildArgs], {
  cwd: packageRoot,
  stdio: ['inherit', 'inherit', 'inherit'],
})
if (build.exitCode !== 0) {
  console.error(`[review] esbuild failed with exit code ${build.exitCode}`)
  process.exit(build.exitCode ?? 1)
}

copyFileSync(join(packageRoot, 'index.html'), join(outDir, 'index.html'))
console.log(`[review] wrote ${join(outDir, 'review.js')}`)

// The HTML carries the bundle inline, so the page is ONE self-contained file.
//
// Not a style choice: an ES module loaded with <script type="module" src="..."> is fetched with CORS,
// and a `file://` page has a null origin, so Chrome blocks it and the page renders blank while the
// file itself looks fine. An *inline* module script is not fetched, so it runs. That is also what
// makes the artifact openable by double-click and inside the JetBrains JCEF webview, which is the
// whole point of a local review display (DEC-027's "one self-contained file" for a report page).
const bundle = readFileSync(join(outDir, 'review.js'), 'utf8')
if (bundle.includes('</script')) {
  // Would close the inline script tag early. Nothing in this page should contain it; fail loudly
  // rather than emit a page that silently truncates.
  console.error('[review] the bundle contains "</script" and cannot be inlined safely')
  process.exit(1)
}
const html = readFileSync(join(packageRoot, 'index.html'), 'utf8')
const inlined = html.replace(
  '<script type="module" src="./review.js"></script>',
  `<script type="module">\n${bundle}\n</script>`,
)
if (inlined === html) {
  console.error('[review] index.html has no <script type="module" src="./review.js"> to replace')
  process.exit(1)
}
writeFileSync(join(outDir, 'index.html'), inlined)
console.log(`[review] wrote ${join(outDir, 'index.html')} (bundle inlined, self-contained)`)
